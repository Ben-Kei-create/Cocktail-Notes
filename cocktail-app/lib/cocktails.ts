export function getCocktailById(id: string): Cocktail | undefined {
  return cocktails.find((c) => c.id === id);
}

export function getRelatedCocktails(cocktail: Cocktail): Cocktail[] {
  return cocktail.related_cocktail_ids
    .map((id) => getCocktailById(id))
    .filter(Boolean) as Cocktail[];
}

export function getFeaturedCocktail(): Cocktail {
  const sorted = [...cocktails].sort((a, b) => a.featured_priority - b.featured_priority);
  return sorted[0];
}

export function searchCocktails(query: string): Cocktail[] {
  const q = query.toLowerCase().trim();
  if (!q) return cocktails;
  return cocktails.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.alternate_names.some((n) => n.toLowerCase().includes(q)) ||
      c.base_spirit.toLowerCase().includes(q) ||
      c.taste_tags.some((t) => t.toLowerCase().includes(q)) ||
      c.mood_tags.some((t) => t.toLowerCase().includes(q)) ||
      c.ingredients.some((i) => i.toLowerCase().includes(q))
  );
}
